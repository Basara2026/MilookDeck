    /// <summary>2バイト符号(行・点の値に 0x20 を足した形: 例 0x7A4E)から外字の文字を返す。表にない場合は「・」。</summary>
    public static string Lookup(int code)
    {
        if (code >= 0x7521 && code <= 0x757E) return Kanji[code - 0x7521];
        if (code >= 0x7621 && code <= 0x764B) return Kanji[code - 0x7621 + 94];
        if (code >= 0x7A4D && code <= 0x7A74) return Symbols[code - 0x7A4D];
        if (code >= 0x7C21 && code <= 0x7C7B) return Symbols[code - 0x7C21 + 40];
        if (code >= 0x7D21 && code <= 0x7D5F) return Symbols[code - 0x7D21 + 131];
        if (code >= 0x7D6E && code <= 0x7D6F) return Symbols[code - 0x7D6E + 194];
        if (code >= 0x7E21 && code <= 0x7E7D) return Symbols[code - 0x7E21 + 196];
        return "・";
    }
